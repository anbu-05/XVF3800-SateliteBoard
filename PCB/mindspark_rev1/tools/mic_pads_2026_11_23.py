"""Mic land-pattern fix: reconnect the frozen mic DATA/CLK routes to the moved pads (2026-11-23).

Why: the mic footprint had its two pad rows 0.838 mm apart (pads at +-0.419 mm from the centre
line). The datasheets give 1.675 mm: Infineon IM69D129FV01 p.12 Fig. 13 (pads 0.522 x 0.725,
rows 1.675 apart, 0.125 mm from the edge) and Knowles SPH0641LM4H-1 p.8 (same numbers); the
"0.838" in Infineon's Fig. 14 is the centre line to a pad row, not row to row. The new footprint
(Mindspark:Knowles_SPH0641LM4H-1_LGA-5_3.5x2.65mm, tools/part_swap_2026_11_23.py) puts the rows
at +-0.8375 mm, so pads 1, 2, 4 and 5 each move 0.4185 mm away from the centre line.

The user's hand routing (user_routing_2026_11_22.json, frozen) ends on the old pad centres.
power_v2 calls reconnect() on the snapshot tracks before laying them:
  * CLK (pad 4): the last segment already runs on the 45-degree line the pad moves along, so it
    simply ends at the new pad centre (shorter by 0.42 mm).
  * DATA (pad 1): the route comes in on a 45-degree diagonal and drops onto the pad with a
    0.1 mm straight stub. The diagonal now stops where a straight stub reaches the new pad centre
    (horizontal or vertical, whichever lands on the diagonal between its ends), keeping the same
    jog style. Stubs stay about 0.1 mm long.
Power pads (2 = SELECT on GND, 3 = GND ring, 5 = VDD) are generated by power_v2 from the board's
pads, so they follow the footprint by themselves.

Run on its own to print the changes:  python3 tools/mic_pads_2026_11_23.py
"""
import json
import math
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from place_tidy import BOARD, Part          # noqa: E402
from sexpr import parse, children           # noqa: E402

MICS = ("MK501", "MK502", "MK503", "MK504")
OLD_ROW, NEW_ROW = 0.419, 0.8375            # pad-row offset from the footprint centre line (local y)
PAD_X = {"1": -1.364, "4": -0.542}          # local x of the DATA and CLK pads
PAD_SIGN = {"1": 1, "4": -1}                # pad 1 sits at +y, pad 4 at -y (footprint frame)
NET = {"1": "DATA", "4": "CLK"}
EPS = 0.005


def board_xy(at, lx, ly):
    """Footprint-local point -> board point (KiCad: y down, rotation counter-clockwise on screen).
    Every mic is on F.Cu, so no mirroring."""
    x, y, r = at
    a = math.radians(-r)
    return (round(x + lx * math.cos(a) - ly * math.sin(a), 4),
            round(y + lx * math.sin(a) + ly * math.cos(a), 4))


def pad_moves(board=BOARD):
    """{(ref, pin): (net, old centre, new centre)} for the DATA and CLK pads of each mic."""
    root = parse(open(board).read())
    out = {}
    for f in children(root, "footprint"):
        p = Part(f)
        if p.ref not in MICS:
            continue
        if p.side != "F.Cu":
            sys.exit(f"{p.ref}: expected on F.Cu")
        for pin in ("1", "4"):
            old = board_xy(p.at, PAD_X[pin], PAD_SIGN[pin] * OLD_ROW)
            new = board_xy(p.at, PAD_X[pin], PAD_SIGN[pin] * NEW_ROW)
            out[(p.ref, pin)] = (f"Net-({p.ref}-{NET[pin]})", old, new)
    if len(out) != 8:
        sys.exit(f"found {len(out)} mic pads, expected 8")
    return out


def same(a, b):
    return abs(a[0] - b[0]) < EPS and abs(a[1] - b[1]) < EPS


def on_segment(p, a, b):
    """p on the straight line a-b, between its ends."""
    cross = (b[0] - a[0]) * (p[1] - a[1]) - (b[1] - a[1]) * (p[0] - a[0])
    if abs(cross) > EPS * math.hypot(b[0] - a[0], b[1] - a[1]):
        return False
    t = ((p[0] - a[0]) * (b[0] - a[0]) + (p[1] - a[1]) * (b[1] - a[1])) / ((b[0] - a[0]) ** 2 + (b[1] - a[1]) ** 2)
    return -EPS <= t <= 1 + EPS


def reconnect(tracks, board=BOARD, log=None):
    """Return a new track list with the mic DATA/CLK ends moved onto the new pad centres.
    tracks: snapshot entries [kind, net, layer, width, pts]. Exits if a route has a shape this
    function does not expect (better than laying copper to the wrong spot)."""
    tracks = [list(t) for t in tracks]
    for (ref, pin), (net, old, new) in sorted(pad_moves(board).items()):
        ends = [t for t in tracks if t[0] == "segment" and t[1] == net
                and (same(t[4][0], old) or same(t[4][-1], old))]
        if len(ends) != 1:
            sys.exit(f"{ref} pad {pin}: expected one track ending on the old pad, found {len(ends)}")
        last = ends[0]
        far = last[4][0] if same(last[4][-1], old) else last[4][-1]
        if on_segment(new, far, old) or on_segment(old, far, new):
            # CLK case: the pad moved along the track's own line
            last[4] = [far, list(new)]
            msg = f"{ref} pad {pin} ({net}): track now ends at {new} (was {old})"
        else:
            # DATA case: a short straight stub (far -> old) after a 45-degree diagonal
            stub_far = far
            diag = [t for t in tracks if t is not last and t[0] == "segment" and t[1] == net
                    and (same(t[4][0], stub_far) or same(t[4][-1], stub_far))]
            if len(diag) != 1:
                sys.exit(f"{ref} pad {pin}: expected one diagonal before the stub, found {len(diag)}")
            d = diag[0]
            start = d[4][0] if same(d[4][-1], stub_far) else d[4][-1]
            dx, dy = stub_far[0] - start[0], stub_far[1] - start[1]
            if abs(abs(dx) - abs(dy)) > EPS:
                sys.exit(f"{ref} pad {pin}: the run before the stub is not at 45 degrees")
            q = None
            # try a horizontal stub (q has the pad's y) and a vertical one (q has the pad's x)
            for qq in ((start[0] + (new[1] - start[1]) * dx / dy, new[1]),
                       (new[0], start[1] + (new[0] - start[0]) * dy / dx)):
                t = ((qq[0] - start[0]) * dx + (qq[1] - start[1]) * dy) / (dx * dx + dy * dy)
                if 0.2 < t <= 1.5 and math.hypot(qq[0] - new[0], qq[1] - new[1]) < 0.3:
                    q = (round(qq[0], 4), round(qq[1], 4))
                    break
            if q is None:
                sys.exit(f"{ref} pad {pin}: no straight stub reaches the new pad from the diagonal")
            d[4] = [list(start), list(q)]
            last[4] = [list(q), list(new)]
            msg = (f"{ref} pad {pin} ({net}): diagonal {tuple(start)} -> {q}, "
                   f"stub {math.hypot(q[0] - new[0], q[1] - new[1]):.3f} mm to {new} (was {old})")
        if log is not None:
            log.append(msg)
        else:
            print(msg)
    return tracks


if __name__ == "__main__":
    snap = json.load(open(os.path.join(HERE, "user_routing_2026_11_22.json")))
    reconnect(snap["tracks"])
