def ref_of(f):
    return str([p[2] for p in children(f, "property") if p[1] == "Reference"][0])


def place():
    root = parse(open(BOARD).read())
    moved = 0
    for f in children(root, "footprint"):
        ref = ref_of(f)
        if ref not in PLACE:
            continue
        x, y, rot, side = PLACE[ref]
        p = Part(f)
        if side == "F.Cu" and p.side != "F.Cu":
            p.flip_to_top()                                   # swaps the footprint's layers too
        fx, fy, fr = p.at
        if abs(fx - x) < 1e-3 and abs(fy - y) < 1e-3 and abs(((fr - rot) + 180) % 360 - 180) < 1e-3:
            continue
        p.place(x, y, rot)
        moved += 1
    open(BOARD, "w").write(dump(root) + "\n")
    print(f"placed {moved} parts")


def snapshot():
    root = parse(open(BOARD).read())
    tracks, vias = [], []
    for kind in ("segment", "arc"):
        for s in children(root, kind):
            d = {c[0]: c[1:] for c in s if isinstance(c, list) and c}
            net = str(d["net"][0])
            if net in POWER or net in LED_LINKS:
                continue
            pts = [(float(d[k][0]), float(d[k][1])) for k in (("start", "mid", "end") if kind == "arc"
                                                                 else ("start", "end"))]
            if kind == "segment" and math.dist(*pts) < 1e-4:
                continue                                          # zero-length leftovers
            tracks.append([kind, net, str(d["layer"][0]), float(d["width"][0]), pts])
    ends = {}
    for kind, net, layer, w, pts in tracks:
        for p in (pts[0], pts[-1]):
            ends.setdefault(net, []).append((p, layer))
    # copper layers of the pads under a point (a via in a pad joins that pad's layer)
    from jog_router import _inside
    pads = {}
    for f in children(root, "footprint"):
        part = Part(f)
        for pd, poly in zip(children(f, "pad"), part.pads()):
            n = child(pd, "net")
            lays = {str(x) for x in (child(pd, "layers") or [])[1:]}
            lays = {"F.Cu", "B.Cu"} if "*.Cu" in lays else lays & {"F.Cu", "B.Cu"}
            if n and lays:
                pads.setdefault(str(n[1]), []).append((poly, lays))
    dropped = []
    for s in children(root, "via"):
        d = {c[0]: c[1:] for c in s if isinstance(c, list) and c}
        net = str(d["net"][0])
        if net in POWER or net in LED_LINKS:
            continue
        at = (float(d["at"][0]), float(d["at"][1]))
        size = (float(d["size"][0]), float(d["drill"][0]))
        lays = {lay for p, lay in ends.get(net, []) if math.dist(at, p) < size[0] / 2}
        lays |= {x for poly, pl in pads.get(net, []) if _inside(at[0], at[1], poly) for x in pl}
        if lays != {"F.Cu", "B.Cu"}:                              # joins nothing on one side
            dropped.append((net, at))
            continue
        vias.append([net, at, size])
    json.dump({"tracks": tracks, "vias": vias}, open(JSON, "w"), indent=0)
    print(f"snapshot: {len(tracks)} tracks, {len(vias)} vias, {len({t[1] for t in tracks})} nets "
          f"-> {os.path.relpath(JSON)}; dropped dangling vias {dropped}")


def load():
    """(tracks, vias, nets) of the snapshot, or None when it has not been written."""
    if not os.path.exists(JSON):
        return None
    d = json.load(open(JSON))
    tracks = [(k, n, lay, w, [tuple(p) for p in pts]) for k, n, lay, w, pts in d["tracks"]]
    vias = [(n, tuple(at), tuple(sz)) for n, at, sz in d["vias"]]
    return tracks, vias, {t[1] for t in tracks} | {v[0] for v in vias}


